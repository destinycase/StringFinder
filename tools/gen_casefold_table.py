"""Generate the Rust case-folding table from a UCD CaseFolding.txt file.

The engine compares text with key(x) = NFC(casefold(NFC(x))). Case folding uses
the full mapping (status C and F, excluding the Turkic T entries). The data file
version must equal unicode-normalization's UNICODE_VERSION; a Rust test checks it.

Usage: python tools/gen_casefold_table.py src/rust_engine/data/CaseFolding-17.0.0.txt
"""

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "rust_engine" / "src" / "casefold_table.rs"


def main(source: str) -> None:
    text = Path(source).read_text(encoding="utf-8")
    version = re.search(r"CaseFolding-(\d+)\.(\d+)\.(\d+)\.txt", text)
    if not version:
        raise SystemExit("version header not found")
    entries = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = (part.strip() for part in line.split(";")[:3])
        if status not in ("C", "F"):
            continue
        backslash = chr(92)
        chars = "".join(f"{backslash}u{{{int(cp, 16):X}}}" for cp in mapping.split())
        entries.append((int(code, 16), chars))
    entries.sort()
    major, minor, patch = version.groups()
    lines = [
        "// @generated by tools/gen_casefold_table.py from CaseFolding-"
        f"{major}.{minor}.{patch}.txt. Do not edit by hand.",
        "",
        f"pub const CASEFOLD_UNICODE_VERSION: (u8, u8, u8) = ({major}, {minor}, {patch});",
        "",
        "/// Full case folding (C + F), sorted by code point.",
        "pub static CASEFOLD: &[(u32, &str)] = &[",
    ]
    lines += [f'    (0x{code:04X}, "{chars}"),' for code, chars in entries]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {len(entries)} entries to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(OUT.parents[1] / "data" / "CaseFolding-17.0.0.txt"))
